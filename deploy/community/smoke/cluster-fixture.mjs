// CybeDefend Community Edition: the project the cluster variant scans.
//
// Each file is planted for one scanner and generated at run time, under a
// temporary folder, never committed: a dependency graph, a workflow linter or
// a code scanner of this repository would otherwise flag every one of them.
// Tested by tests/cluster.test.mjs.

import { randomBytes, randomInt } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

// Opengrep: eval of user input.
const APP_PY = `# Generated by the CybeDefend smoke (cluster variant): Opengrep reports this eval.
print(eval(input()))
`;

// Trivy (config): no USER, so the image runs as root.
const DOCKERFILE = `# Generated by the CybeDefend smoke (cluster variant): no USER, the image runs as root.
FROM python:3.12-slim
COPY . /app
CMD ["python", "/app/app.py"]
`;

// zizmor: pull_request_target checking out the pull request's head.
const CI_YML = `# Generated by the CybeDefend smoke (cluster variant): zizmor reports this
# workflow, which checks out a pull request's head under pull_request_target.
name: ci
on:
  pull_request_target:
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          ref: \${{ github.event.pull_request.head.sha }}
      - run: python app.py
`;

// Trivy (filesystem): a django version with known vulnerabilities.
const REQUIREMENTS = 'django==2.2.0\n';

const B32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
const ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const pick = (alphabet, n) => Array.from({ length: n }, () => alphabet[randomInt(alphabet.length)]).join('');

/**
 * The secret project's `config.py`: fake keys generated at each run, in the
 * shapes Gitleaks recognises (an AWS access key id, a GitHub token).
 */
export function fakeSecretFile() {
  return [
    '# Generated by the CybeDefend smoke at run time: fake keys, valid nowhere.',
    `AWS_ACCESS_KEY_ID = "AKIA${pick(B32, 16)}"`,
    `AWS_SECRET_ACCESS_KEY = "${randomBytes(30).toString('base64')}"`,
    `GITHUB_TOKEN = "ghp_${pick(ALNUM, 36)}"`,
    '',
  ].join('\n');
}

/** The files of `project`'s archive, at its root; the secret project also gets a fresh config.py. */
export function fixtureFiles(project) {
  const files = [
    { name: 'app.py', content: Buffer.from(APP_PY) },
    { name: 'Dockerfile', content: Buffer.from(DOCKERFILE) },
    { name: 'requirements.txt', content: Buffer.from(REQUIREMENTS) },
    { name: '.github/workflows/ci.yml', content: Buffer.from(CI_YML) },
  ];
  if (project === 'secret') files.push({ name: 'config.py', content: Buffer.from(fakeSecretFile()) });
  return files;
}

/** Writes fixtureFiles(project) under `dir`. */
export function writeFixtureRepo(dir, project) {
  for (const { name, content } of fixtureFiles(project)) {
    const path = join(dir, ...name.split('/'));
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
