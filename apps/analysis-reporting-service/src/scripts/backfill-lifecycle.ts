/**
 * One-time backfill: reconstruct the finding lifecycle (first/last detection,
 * triage actor and timestamp, resolution, dismissal reason) from the two
 * history tables, for all six detection families.
 *
 * Usage:
 *   cd analysis-reporting-service
 *   pnpm exec ts-node src/scripts/backfill-lifecycle.ts
 *   pnpm exec ts-node src/scripts/backfill-lifecycle.ts --dry-run
 *   pnpm exec ts-node src/scripts/backfill-lifecycle.ts --table=sast
 *   pnpm exec ts-node src/scripts/backfill-lifecycle.ts --rebuild   # see below
 *
 * WHY IT EXISTS: without it, `GET /organization/:organizationId/findings` would have to correlate six
 * window-function subqueries against `history_item` on every page.
 *
 * WHY IT DOES NOT BOOT NEST: the application context loads its secrets through
 * the edition's secrets source and every module with them, so a one-off has to
 * construct its own connection. Mirrors `backfill-fingerprints.ts` and `src/core/config/data-source.ts`.
 *
 * WHY IT NEVER GUESSES: `history_item.date` is `datetime` with
 * `DATETIME_PRECISION = 0` — whole seconds. Two rows written in the same second
 * are indistinguishable in order. Every place that would need such an order is
 * counted and left NULL rather than resolved arbitrarily; a hole self-heals on
 * the next triage, a wrong value does not.
 *
 * TIMEZONE — read this before touching any date in here.
 *
 * Two kinds of column meet in this script and they are NOT on the same base:
 *
 *   - `history_item.date` and `vulnerability_detection_history.detectedAt` are
 *     `datetime(0)`: a wall clock in the timezone of whichever PROCESS wrote
 *     the row, with no offset recorded anywhere.
 *   - `createdAt` and the six lifecycle columns are `TIMESTAMP`: true instants.
 *     `createdAt` is generated by MySQL itself (`DEFAULT_GENERATED
 *     CURRENT_TIMESTAMP`; TypeORM deliberately sends no value — see the comment
 *     in its InsertQueryBuilder, "we don't do it because this constant is
 *     already in default value of the column"), so it is expressed in the
 *     SESSION timezone.
 *
 * Assigning a DATETIME to a TIMESTAMP re-reads those digits in the session
 * timezone, i.e. silently declares that the writing process ran on the
 * session's offset. Measured on the local corpus, it does not:
 * `MIN(detectedAt) - createdAt` is 0/1/2 s on some rows and 3600/7200 s on
 * others IN THE SAME TABLE — this database was written by a UTC process and by
 * a Europe/Paris one at different times. There is therefore NO global
 * conversion, and the only per-row anchor is `createdAt`.
 *
 * So the rule this script follows:
 *   1. every value it writes is a `'YYYY-MM-DD HH:MM:SS'` literal in the
 *      SESSION timezone, passed as a string — the driver's own timezone never
 *      enters the picture, in either direction (all reads go through
 *      `DATE_FORMAT`, all arithmetic through {@link parseSqlTimestamp}, which
 *      is UTC-based and therefore also immune to DST);
 *   2. `first_detected_at` is anchored on `createdAt`; the ingestion trail
 *      contributes only its SPAN. A span is base-invariant ONLY while the base
 *      is the same at both ends of the trail — a difference of two literals
 *      cancels the offset only if it is the same offset. It is not, in general:
 *      a process writing `datetime(0)` on any non-UTC zone changes offset at
 *      every DST transition, and a corpus can flip from +3600/+7200 to +0
 *      mid-life. The offset of each SCAN is
 *      recoverable ({@link loadScanOffsets}), so a trail whose two ends were
 *      written on different offsets has that difference removed from its span
 *      ({@link computeDetectionBounds}'s `baseDriftSeconds`) and is counted;
 *      a trail whose ends cannot be attributed to a known offset is counted
 *      too, and its span left as recorded rather than guessed at;
 *   3. `triaged_at`/`resolved_at` come from `history_item.date`, which has no
 *      anchor at all — they keep their recorded wall clock, clamped so they can
 *      never predate the detection. The residual uncertainty is bounded by the
 *      writing process's offset and is zero on any all-UTC deployment.
 *
 * WHAT IT MAY OVERWRITE. This script is not the only writer of these columns.
 * The live re-detection path and the triage handlers write them too, and they
 * know things the two history tables never recorded — container has no
 * ingestion trail at all, and a re-triage that does not change the status
 * leaves no `status_change` row. So the backfill only ever ADDS evidence:
 * `first_detected_at` may move earlier and `last_detected_at` later
 * ({@link mergeDetectionBounds}), and a stored triage NEWER than the last
 * reconstructable transition is left alone ({@link decideTriageWrite}).
 * `--rebuild` opts out of both, for the one case where the stored values are
 * themselves the damage.
 */
