export interface StoredTriage {
  triagedAt: string | null;
  triagedBy: string | null;
  triagedByType: string | null;
  resolvedAt: string | null;
  dismissalReason: string | null;
}

export type TriageDecision = 'write' | 'unchanged' | 'preserve-newer';

/**
 * Whether the reconstructed triage may replace the stored one.
 *
 * `history_item` is not a complete record of triage. `handleUpdateSast` /
 * `handleUpdateIac` / `handleUpdateCicd` / `handleUpdateSecret` (and the sca and
 * container equivalents) append a `status_change` row ONLY when
 * `dto.status !== oldStatus`. Re-triaging a finding that is already `ignored` —
 * changing the dismissal reason, or a human overriding the agent's verdict —
 * therefore leaves NO history row at all, and the reconstruction keeps
 * describing the older transition. Replaying it would revert
 * `triaged_by_type` from `user` to `agent` and put the agent's text back over a
 * human risk acceptance: in an audit export that is a falsified accountability
 * record, which is worse than a missing one.
 *
 * So a stored triage that is strictly NEWER than the last reconstructable
 * transition wins, and one that shares its second loses (same source row, so
 * the fresh derivation of the other columns is the better reading of it — this
 * is how the agent's verdicts were reclassified from `system` to `agent`).
 */
export function decideTriageWrite(
  stored: StoredTriage | null,
  computed: StoredTriage,
): TriageDecision {
  if (stored === null) return 'write';
  if (stored.triagedAt !== null) {
    if (computed.triagedAt === null) return 'preserve-newer';
    if (stored.triagedAt > computed.triagedAt) return 'preserve-newer';
  }
  const same =
    stored.triagedAt === computed.triagedAt &&
    (stored.triagedBy ?? null) === computed.triagedBy &&
    (stored.triagedByType ?? null) === computed.triagedByType &&
    stored.resolvedAt === computed.resolvedAt &&
    (stored.dismissalReason ?? null) === computed.dismissalReason;
  return same ? 'unchanged' : 'write';
}

/**
 * Lift a literal that sits before `floor`, leave it alone otherwise.
 *
 * `history_item.date` has no anchor, so a triage recorded by a process behind
 * the session's offset reads as happening before the finding was detected. That
 * ordering is impossible, so it is corrected; the remaining skew is not
 * invented away.
 */
export function clampNotBefore(
  value: string | null,
  floor: string | null,
): string | null {
  if (value === null || floor === null) return value;
  return parseSqlTimestamp(value).getTime() < parseSqlTimestamp(floor).getTime()
    ? floor
    : value;
}

/**
 * Every real UTC offset is a whole number of quarter hours, so an offset
 * estimate that is not near one is not an offset.
 */
const TZ_OFFSET_GRANULARITY_S = 900;

/**
 * The real UTC offset range: UTC-12:00 (Baker Island) to UTC+14:00
 * (Kiritimati). Anything outside is elapsed time wearing a timezone's clothes.
 */
const MIN_UTC_OFFSET_S = -12 * 3600;
const MAX_UTC_OFFSET_S = 14 * 3600;

/**
 * How far an estimate may sit from a quarter hour and still be read as one.
 * The estimates come from a detection's CREATION sighting, where the gap
 * between inserting the detection row and inserting its first trail row is
 * sub-second — measured at 0-2 s on every local scan.
 */
const OFFSET_SNAP_TOLERANCE_S = 60;

/**
 * Read a `detectedAt - createdAt` estimate as the writing process's UTC offset,
 * or refuse to.
 *
 * The estimate is only an offset when the trail row records the sighting that
 * CREATED the detection. A scan that merely re-detected an old finding produces
 * elapsed time instead (64586 s, 1417605 s, … on the local corpus), and elapsed
 * time must never be mistaken for a timezone: it would fabricate a base change
 * and warp the span it is supposed to correct. Anything further than
 * {@link OFFSET_SNAP_TOLERANCE_S} from a quarter hour is therefore discarded,
 * not rounded into one.
 */
export function snapUtcOffsetSeconds(estimate: number | null): number | null {
  if (estimate === null || !Number.isFinite(estimate)) return null;
  const snapped =
    Math.round(estimate / TZ_OFFSET_GRANULARITY_S) * TZ_OFFSET_GRANULARITY_S;
  if (Math.abs(estimate - snapped) > OFFSET_SNAP_TOLERANCE_S) return null;
  // The grid test alone does not separate an offset from elapsed time: elapsed
  // time lands on a quarter hour roughly once every 900 s. An estimate of
  // 966600 s — 11 days 4 h, an exact multiple of 900 — would be accepted as a
  // timezone. Magnitude is the discriminator the grid cannot be.
  if (snapped < MIN_UTC_OFFSET_S || snapped > MAX_UTC_OFFSET_S) return null;
  return snapped;
}

/**
 * The last second of `status_change` rows, and whether that second is readable.
 *
 * `date` is second-precision, so two transitions written in the same second
 * carry no order. When they disagree on the resulting state, the "latest" one
 * is a coin flip — `state` is null and the caller must not invent one.
 */
export function latestTransition(items: HistoryRow[]): {
  latest: HistoryRow | null;
  tied: HistoryRow[];
  state: string | null;
  ambiguous: boolean;
} {
  const transitions = items
    .filter((i) => i.type === 'status_change')
    .sort((a, b) => a.date.getTime() - b.date.getTime());

  if (transitions.length === 0) {
    return { latest: null, tied: [], state: null, ambiguous: false };
  }

  const lastSecond = transitions[transitions.length - 1].date.getTime();
  const tied = transitions.filter((t) => t.date.getTime() === lastSecond);
  const ambiguous = new Set(tied.map((t) => t.value)).size > 1;
  const latest = tied[tied.length - 1];

  return { latest, tied, state: ambiguous ? null : latest.value, ambiguous };
}

export function resolveTriageFromHistory(items: HistoryRow[]): TriageSnapshot {
  const { latest, tied, state, ambiguous } = latestTransition(items);
  if (latest === null) return { ...EMPTY };

  const lastSecond = latest.date.getTime();

  // The actor survives a value tie when every tied row agrees on it.
  const actorIds = new Set(tied.map((t) => actorId(t)));
  const actorTypes = new Set(tied.map((t) => actorType(t)));
  const actorAgreed = actorIds.size === 1 && actorTypes.size === 1;

  // history_item.date is DATETIME (second precision) and the status_change and
  // its comment are written from the same `const date = new Date()` in each
  // handleUpdate* handler, so equality on the second is the only join
  // available. Ambiguity is reported, never guessed.
  const sameSecondComments =
    state === 'ignored'
      ? items.filter(
          (i) => i.type === 'comment' && i.date.getTime() === lastSecond,
        )
      : [];

  return {
    triagedAt: latest.date,
    triagedBy: actorAgreed ? actorId(latest) : null,
    triagedByType: actorAgreed ? actorType(latest) : null,
    resolvedAt: state === 'resolved' ? latest.date : null,
    dismissalReason:
      sameSecondComments.length === 1 ? sameSecondComments[0].value : null,
    ambiguousComment: sameSecondComments.length > 1,
    ambiguousTransition: ambiguous,
  };
}

