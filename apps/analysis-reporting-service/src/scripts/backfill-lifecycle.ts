/**
 * The UTC offset each scan's writer ran on, keyed by `scanId`.
 *
 * `vulnerability_detection_history` records no offset and has no `createdAt` of
 * its own, so a trail row carries no anchor — but the detection it points at
 * does. On the sighting that CREATED a detection, `detectedAt - createdAt` is
 * the writing process's offset plus a sub-second insert gap, and every trail
 * row of one scan was written by one process. So one measurement per scan dates
 * the whole scan.
 *
 * Restricting to creation sightings is what makes the measurement sound: on any
 * other row the same difference is elapsed time.
 * {@link snapUtcOffsetSeconds} throws out whatever slips through.
 *
 * A corpus can show +3600/+7200 for every scan up to a date and +0 for every
 * scan after it: its base flipped mid-life.
 */
async function loadScanOffsets(ds: DataSource): Promise<Map<string, number>> {
  const offsets = new Map<string, number>();
  for (const spec of Object.values(FAMILIES)) {
    const fk = spec.detectionHistoryFk;
    if (!fk) continue;
    const rows: Array<{ scanId: string; estimate: number | null }> =
      await ds.query(
        `SELECT h.scanId AS scanId,
                MIN(TIMESTAMPDIFF(SECOND, d.createdAt, h.detectedAt)) AS estimate
           FROM vulnerability_detection_history h
           JOIN \`${spec.table}\` d ON d.id = h.${fk}
           JOIN (SELECT ${fk} AS did, MIN(detectedAt) AS firstSeen
                   FROM vulnerability_detection_history
                  WHERE ${fk} IS NOT NULL
                  GROUP BY ${fk}) f
             ON f.did = h.${fk} AND f.firstSeen = h.detectedAt
          GROUP BY h.scanId`,
      );
    for (const row of rows) {
      const offset = snapUtcOffsetSeconds(
        row.estimate === null ? null : Number(row.estimate),
      );
      if (offset === null) continue;
      // A scan seen through two families must give the same answer; the
      // tighter estimate is the one less polluted by the insert gap.
      const known = offsets.get(row.scanId);
      offsets.set(
        row.scanId,
        known === undefined ? offset : Math.min(known, offset),
      );
    }
  }
  return offsets;
}

/**
 * One page of detections with their `createdAt` and their trail aggregate.
 *
 * Everything comes back as a `DATE_FORMAT` STRING, never as a driver `Date`:
 * mysql2 renders a Date parameter in the PROCESS timezone and MySQL then reads
 * that literal back in the SESSION timezone, so a Date round trip through a
 * TIMESTAMP column silently moves the instant by the difference between the
 * two. Strings keep the whole pipeline on the session's base.
 */
async function* detectionBoundsRows(
  ds: DataSource,
  spec: FamilySpec,
): AsyncGenerator<BoundsRow[]> {
  const fk = spec.detectionHistoryFk;
  // The two end scans come along with the two bounds: they are what dates the
  // base each end was written on (see loadScanOffsets). MIN(scanId) breaks the
  // tie when two scans share the same second — deterministic, and the residual
  // is one second of a span, not an hour of it.
  const trailJoin = fk
    ? `LEFT JOIN (SELECT t.did AS did, t.first_seen AS first_seen, t.last_seen AS last_seen,
                         MIN(f.scanId) AS first_scan, MIN(l.scanId) AS last_scan
                    FROM (SELECT ${fk} AS did,
                                 MIN(detectedAt) AS first_seen,
                                 MAX(detectedAt) AS last_seen
                            FROM vulnerability_detection_history
                           WHERE ${fk} IS NOT NULL
                           GROUP BY ${fk}) t
                    JOIN vulnerability_detection_history f
                      ON f.${fk} = t.did AND f.detectedAt = t.first_seen
                    JOIN vulnerability_detection_history l
                      ON l.${fk} = t.did AND l.detectedAt = t.last_seen
                   GROUP BY t.did, t.first_seen, t.last_seen) h ON h.did = d.id`
    : '';
  const trailCols = fk
    ? `DATE_FORMAT(h.first_seen, '${SQL_TS_FORMAT}') AS trailFirst,
       DATE_FORMAT(h.last_seen,  '${SQL_TS_FORMAT}') AS trailLast,
       h.first_scan AS firstScanId, h.last_scan AS lastScanId`
    : `NULL AS trailFirst, NULL AS trailLast,
       NULL AS firstScanId, NULL AS lastScanId`;

  let cursor = '';
  for (;;) {
    const rows: BoundsRow[] = await ds.query(
      `SELECT d.id AS id,
              DATE_FORMAT(d.createdAt, '${SQL_TS_FORMAT_US}') AS createdAt,
              DATE_FORMAT(d.first_detected_at, '${SQL_TS_FORMAT}') AS storedFirst,
              DATE_FORMAT(d.last_detected_at,  '${SQL_TS_FORMAT}') AS storedLast,
              ${trailCols}
         FROM \`${spec.table}\` d
         ${trailJoin}
        WHERE d.id > ?
        ORDER BY d.id
        LIMIT ${ID_PAGE_SIZE}`,
      [cursor],
    );
    if (rows.length === 0) return;
    yield rows;
    cursor = rows[rows.length - 1].id;
  }
}

/**
 * `first_detected_at` / `last_detected_at`, anchored on `createdAt`.
 *
 * Deliberately, the trail's `MIN/MAX(detectedAt)` is never copied as is: it
 * is a `datetime(0)` wall clock in the WRITING PROCESS's timezone, and a
 * `TIMESTAMP` column re-reads those digits in the SESSION timezone, which can
 * put a row hours AFTER its own `createdAt`. See the TIMEZONE block at the top
 * of the file; {@link computeDetectionBounds} carries the rule.
 *
 * Deliberately, the UPDATE is not guarded with
 * `WHERE d.first_detected_at IS NULL` plus a `createdAt` fallback — a
 * second run would find every row already stamped and can never pick up newly
 * ingested history. Both bounds are recomputed from scratch on every run, and
 * merged with the stored ones by {@link mergeDetectionBounds} so the recompute
 * can widen the window but never narrow it. That is what makes the script
 * self-healing without being destructive: that guard would have frozen
 * the script, and recomputing unconditionally would have reverted every stamp
 * the live re-detection path wrote (fatally so for container, which has no
 * ingestion trail to re-derive from).
 */
async function backfillDetectionBounds(
  ds: DataSource,
  spec: FamilySpec,
  scanOffsets: Map<string, number>,
  opts: { dryRun: boolean; rebuild: boolean },
): Promise<{
  fromHistory: number;
  fromCreatedAt: number;
  clockSkewed: number;
  baseChanged: number;
  unanchoredTrails: number;
  written: number;
}> {
  let fromHistory = 0;
  let fromCreatedAt = 0;
  let clockSkewed = 0;
  let baseChanged = 0;
  let unanchoredTrails = 0;
  let written = 0;

  for await (const page of detectionBoundsRows(ds, spec)) {
    const writes: Array<{ id: string; first: string; last: string }> = [];
    for (const row of page) {
      // What the two ends of the trail were written on. A trail whose ends
      // disagree spans a DST transition (or a redeploy onto another zone), and
      // its raw span over-states the window by exactly that difference.
      const firstOffset =
        row.firstScanId === null ? undefined : scanOffsets.get(row.firstScanId);
      const lastOffset =
        row.lastScanId === null ? undefined : scanOffsets.get(row.lastScanId);
      const hasTrail = row.trailFirst !== null && row.trailLast !== null;
      let drift = 0;
      if (hasTrail) {
        if (firstOffset === undefined || lastOffset === undefined) {
          // Not correctable and not pretended to be: the span is left as
          // recorded and the row is reported.
          unanchoredTrails++;
        } else if (
          Math.abs(lastOffset - firstOffset) >= TZ_OFFSET_GRANULARITY_S
        ) {
          drift = lastOffset - firstOffset;
          baseChanged++;
        }
      }

      const bounds = computeDetectionBounds(
        row.createdAt,
        row.trailFirst,
        row.trailLast,
        drift,
      );
      if (bounds.spanFrom === 'trail') fromHistory++;
      else fromCreatedAt++;
      if (
        bounds.trailSkewSeconds !== null &&
        Math.abs(bounds.trailSkewSeconds) >= TZ_OFFSET_GRANULARITY_S
      ) {
        clockSkewed++;
      }

      // The reconstruction only ADDS to what is stored — see
      // mergeDetectionBounds. A row that comes out unchanged is NOT rewritten:
      // both `updateAt` (sast/iac/cicd/secret) and `updatedAt` (sca/container)
      // are `on update CURRENT_TIMESTAMP`, and `organization-overview.service`
      // and `result.service` group their daily activity series on exactly those
      // columns — a backfill that touches every row moves the whole corpus into
      // today's bucket and flattens the charts. This also makes a second run
      // write literally nothing.
      const merged = opts.rebuild
        ? {
            first: bounds.firstDetectedAt,
            last: bounds.lastDetectedAt,
            changed:
              row.storedFirst !== bounds.firstDetectedAt ||
              row.storedLast !== bounds.lastDetectedAt,
          }
        : mergeDetectionBounds(
            { first: row.storedFirst, last: row.storedLast },
            { first: bounds.firstDetectedAt, last: bounds.lastDetectedAt },
          );
      if (!merged.changed) continue;
      writes.push({ id: row.id, first: merged.first, last: merged.last });
    }
    written += writes.length;
    if (!opts.dryRun) await writeDetectionBounds(ds, spec.table, writes);
  }

  return {
    fromHistory,
    fromCreatedAt,
    clockSkewed,
    baseChanged,
    unanchoredTrails,
    written,
  };
}

/** One statement per page, not per row: `CASE id WHEN … THEN …`. */
async function writeDetectionBounds(
  ds: DataSource,
  table: string,
  rows: Array<{ id: string; first: string; last: string }>,
): Promise<void> {
  if (rows.length === 0) return;
  const when = rows.map(() => 'WHEN ? THEN ?').join(' ');
  const marks = rows.map(() => '?').join(', ');
  await ds.query(
    `UPDATE \`${table}\`
        SET first_detected_at = CASE id ${when} END,
            last_detected_at  = CASE id ${when} END
      WHERE id IN (${marks})`,
    [
      ...rows.flatMap((r) => [r.id, r.first]),
      ...rows.flatMap((r) => [r.id, r.last]),
      ...rows.map((r) => r.id),
    ],
  );
}

/** Detection ids that carry at least one `history_item`, keyset-paged. */
async function* detectionIdsWithHistory(
  ds: DataSource,
  fk: string,
): AsyncGenerator<string[]> {
  let cursor = '';
  for (;;) {
    const rows: Array<{ id: string }> = await ds.query(
      `SELECT DISTINCT ${fk} AS id FROM history_item
        WHERE ${fk} IS NOT NULL AND ${fk} > ?
        ORDER BY ${fk} LIMIT ${ID_PAGE_SIZE}`,
      [cursor],
    );
    if (rows.length === 0) return;
    yield rows.map((r) => r.id);
    cursor = rows[rows.length - 1].id;
  }
}

async function backfillTriage(
  ds: DataSource,
  spec: FamilySpec,
  opts: { dryRun: boolean; rebuild: boolean },
): Promise<{
  triaged: number;
  resolved: number;
  dismissalReasons: number;
  clampedTriage: number;
  triageWritten: number;
  triagePreserved: number;
  ambiguousComment: number;
  ambiguousTransition: number;
  stateMismatch: number;
}> {
  const fk = spec.historyFk;
  let triaged = 0;
  let resolved = 0;
  let dismissalReasons = 0;
  let clampedTriage = 0;
  let triageWritten = 0;
  let triagePreserved = 0;
  let ambiguousComment = 0;
  let ambiguousTransition = 0;
  let stateMismatch = 0;

  for await (const ids of detectionIdsWithHistory(ds, fk)) {
    const marks = ids.map(() => '?').join(', ');
    // `ORDER BY date, id` only makes the row order DETERMINISTIC; it does not
    // make a same-second tie meaningful. resolveTriageFromHistory is what
    // refuses to read an order into it.
    //
    // `date` is read as a formatted STRING for the reason given in the TIMEZONE
    // block: a driver `Date` would carry the process timezone into a column
    // MySQL reads in the session timezone.
    const rows: Array<
      Omit<HistoryRow, 'date'> & { detectionId: string; date: string | null }
    > = await ds.query(
      `SELECT ${fk} AS detectionId, type, value,
              DATE_FORMAT(date, '${SQL_TS_FORMAT}') AS date, userId, source
         FROM history_item
        WHERE ${fk} IN (${marks})
        ORDER BY ${fk}, date ASC, id ASC`,
      ids,
    );
    // `first_detected_at` was written by backfillDetectionBounds just above and
    // is the floor every triage timestamp is clamped to. The stored triage
    // columns come along so an unchanged row can be left alone (see the note on
    // `updateAt` in backfillDetectionBounds).
    const states: Array<{
      id: string;
      currentState: string;
      firstDetectedAt: string | null;
      triagedAt: string | null;
      triagedBy: string | null;
      triagedByType: string | null;
      resolvedAt: string | null;
      dismissalReason: string | null;
    }> = await ds.query(
      `SELECT id, currentState,
              DATE_FORMAT(first_detected_at, '${SQL_TS_FORMAT}') AS firstDetectedAt,
              DATE_FORMAT(triaged_at, '${SQL_TS_FORMAT}') AS triagedAt,
              triaged_by AS triagedBy, triaged_by_type AS triagedByType,
              DATE_FORMAT(resolved_at, '${SQL_TS_FORMAT}') AS resolvedAt,
              dismissal_reason AS dismissalReason
         FROM \`${spec.table}\` WHERE id IN (${marks})`,
      ids,
    );
    const stateById = new Map(states.map((s) => [s.id, s.currentState]));
    const storedById = new Map(states.map((s) => [s.id, s]));

    const byDetection = new Map<string, HistoryRow[]>();
    for (const r of rows) {
      // A history row with no date carries no position in the timeline.
      if (!r.date) continue;
      const bucket = byDetection.get(r.detectionId) ?? [];
      bucket.push({
        type: r.type,
        value: r.value,
        date: parseSqlTimestamp(r.date),
        userId: r.userId ?? null,
        source: r.source ?? null,
      });
      byDetection.set(r.detectionId, bucket);
    }

    for (const [id, items] of byDetection) {
      const snapshot = resolveTriageFromHistory(items);
      if (snapshot.ambiguousComment) ambiguousComment++;
      if (snapshot.ambiguousTransition) ambiguousTransition++;

      // A detection whose history holds no status_change has no reconstructable
      // triage. Writing five NULLs over it would tell the export nothing it does
      // not already know, and would erase whatever the live write path (task 6)
      // had stamped. Skipping is strictly safer.
      if (snapshot.triagedAt === null) continue;

      // Honesty check, not a correction: if the last readable transition
      // disagrees with the row's own `currentState`, some write path changed the
      // state without leaving a history row, and the reconstructed lifecycle is
      // describing a different story than the row does.
      const { state } = latestTransition(items);
      const currentState = stateById.get(id);
      if (
        state !== null &&
        currentState !== undefined &&
        state !== currentState
      ) {
        stateMismatch++;
      }

      triaged++;
      if (snapshot.resolvedAt) resolved++;
      if (snapshot.dismissalReason) dismissalReasons++;

      // `history_item.date` is a wall clock with no recorded offset, so it
      // cannot be moved onto the session's base — but a triage that predates
      // the detection is impossible, and that is the failure mode a deployment
      // whose history was written BEHIND the session offset produces.
      const stored = storedById.get(id);
      const floor = stored?.firstDetectedAt ?? null;
      const rawTriagedAt = formatSqlTimestamp(snapshot.triagedAt);
      const triagedAt = clampNotBefore(rawTriagedAt, floor);
      const resolvedAt = clampNotBefore(
        snapshot.resolvedAt ? formatSqlTimestamp(snapshot.resolvedAt) : null,
        floor,
      );
      if (triagedAt !== rawTriagedAt) clampedTriage++;

      const computed: StoredTriage = {
        triagedAt,
        triagedBy: snapshot.triagedBy,
        triagedByType: snapshot.triagedByType,
        resolvedAt,
        dismissalReason: snapshot.dismissalReason,
      };
      // The default refuses to overwrite a triage newer than the last
      // status_change (see decideTriageWrite); `--rebuild` accepts losing it in
      // exchange for a derivation that owes nothing to the stored values.
      // `unchanged` is honoured either way — that is the guard that keeps the
      // backfill out of the `updateAt` activity buckets.
      const decision = decideTriageWrite(stored ?? null, computed);
      if (decision === 'preserve-newer' && !opts.rebuild) {
        triagePreserved++;
        continue;
      }
      if (decision === 'unchanged') continue;
      triageWritten++;

      if (!opts.dryRun) {
        await ds.query(
          `UPDATE \`${spec.table}\`
              SET triaged_at = ?, triaged_by = ?, triaged_by_type = ?,
                  resolved_at = ?, dismissal_reason = ?
            WHERE id = ?`,
          [
            triagedAt,
            snapshot.triagedBy,
            snapshot.triagedByType,
            resolvedAt,
            snapshot.dismissalReason,
            id,
          ],
        );
      }
    }
  }

  return {
    triaged,
    resolved,
    dismissalReasons,
    clampedTriage,
    triageWritten,
    triagePreserved,
    ambiguousComment,
    ambiguousTransition,
    stateMismatch,
  };
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const dryRun = argv.includes('--dry-run');
  const rebuild = argv.includes('--rebuild');
  const only = argv.find((a) => a.startsWith('--table='))?.split('=')[1];
  const opts = { dryRun, rebuild };

  const ds = buildDataSource();
  await ds.initialize();
  const outcomes: FamilyOutcome[] = [];

  try {
    const scanOffsets = await loadScanOffsets(ds);
    console.log(
      `[backfill-lifecycle] dated ${scanOffsets.size} scans by the UTC offset ` +
        `their trail rows were written on: ` +
        `${[...new Set(scanOffsets.values())].sort((a, b) => a - b).join('s, ')}s`,
    );

    for (const [family, spec] of Object.entries(FAMILIES)) {
      if (only && only !== family) continue;

      const [{ n: rows }] = await ds.query(
        `SELECT COUNT(*) n FROM \`${spec.table}\``,
      );
      const bounds = await backfillDetectionBounds(ds, spec, scanOffsets, opts);
      const triage = await backfillTriage(ds, spec, opts);

      outcomes.push({
        family,
        table: spec.table,
        rows: Number(rows),
        detectedFromHistory: bounds.fromHistory,
        detectedFromCreatedAt: bounds.fromCreatedAt,
        clockSkewedTrails: bounds.clockSkewed,
        baseChangedTrails: bounds.baseChanged,
        unanchoredTrails: bounds.unanchoredTrails,
        boundsWritten: bounds.written,
        ...triage,
      });

      console.log(
        `[backfill-lifecycle] ${spec.table}: ${rows} rows, ` +
          `${bounds.fromHistory} bounded by ingestion history, ` +
          `${bounds.fromCreatedAt} bounded by createdAt, ` +
          `${triage.triaged} triage snapshots, ` +
          `${bounds.written + triage.triageWritten} rows actually written`,
      );
    }

    const sum = (pick: (o: FamilyOutcome) => number) =>
      outcomes.reduce((a, o) => a + pick(o), 0);

    console.log('\n=== LIFECYCLE BACKFILL REPORT ===');
    for (const o of outcomes) {
      console.log(
        `${o.table.padEnd(38)} rows=${o.rows} ` +
          `fromHistory=${o.detectedFromHistory} fromCreatedAt=${o.detectedFromCreatedAt} ` +
          `clockSkewedTrails=${o.clockSkewedTrails} ` +
          `baseChangedTrails=${o.baseChangedTrails} ` +
          `unanchoredTrails=${o.unanchoredTrails} ` +
          `written=${o.boundsWritten}+${o.triageWritten} ` +
          `triaged=${o.triaged} resolved=${o.resolved} ` +
          `dismissalReason=${o.dismissalReasons} ` +
          `clampedTriage=${o.clampedTriage} ` +
          `triagePreserved=${o.triagePreserved} ` +
          `ambiguousComment=${o.ambiguousComment} ` +
          `ambiguousTransition=${o.ambiguousTransition} ` +
          `stateMismatch=${o.stateMismatch}`,
      );
    }

    console.log(
      `\n${sum((o) => o.ambiguousComment)} detections had an ambiguous dismissal comment ` +
        `and were left null.\n` +
        `${sum((o) => o.ambiguousTransition)} detections had two or more differing status_change ` +
        `rows inside one second; their resolved_at and dismissal_reason were left null.\n` +
        `${sum((o) => o.stateMismatch)} detections disagree with their own currentState — ` +
        `the last status_change is not what the row currently says.\n` +
        `${sum((o) => o.clockSkewedTrails)} detections have an ingestion trail written by a ` +
        `process at least ${TZ_OFFSET_GRANULARITY_S}s off the database session's offset; their ` +
        `bounds were re-anchored on createdAt, and their triaged_at/resolved_at carry the same ` +
        `unrecoverable offset because history_item.date has no anchor.\n` +
        `${sum((o) => o.baseChangedTrails)} detections have a trail whose two ends were written ` +
        `on DIFFERENT offsets (a DST transition, or a move between zones); the difference was ` +
        `removed from their span, which would otherwise have been wrong by exactly it.\n` +
        `${sum((o) => o.unanchoredTrails)} detections have a trail one of whose end scans could ` +
        `not be dated — no detection was created by that scan, so its offset is unknown. Their ` +
        `span is left as recorded and is only correct if no offset changed inside it.\n` +
        `${sum((o) => o.clampedTriage)} triage timestamps predated their own first detection and ` +
        `were lifted to it.\n` +
        `${sum((o) => o.triagePreserved)} detections carry a triage NEWER than their last ` +
        `status_change and were left untouched — a re-triage that does not change the status ` +
        `writes no history row, so the reconstruction is the stale one there.` +
        (rebuild
          ? '\n\n(--rebuild: stored values were ignored, not merged)'
          : '') +
        (dryRun ? '\n\n(--dry-run: nothing was written)' : ''),
    );
  } finally {
    await ds.destroy();
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
