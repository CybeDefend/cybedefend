import type { ParityAllowance } from '@cybedefend/db-dialect';

/**
 * The differences schema-parity.live.spec.ts accepts between the frozen MySQL
 * track and the PostgreSQL baseline, one line each with its reason. Nothing
 * goes here without a reason a reviewer can check; an entry that matches
 * nothing fails the spec.
 *
 * Needing no allowance: the prefix-length indexes of
 * 1804000001000-AddPerformanceIndexes (readSchema compares column lists, not
 * prefix lengths); mediumblob ↔ bytea and float ↔ double precision
 * (normalised to one type); the four detection `updateAt` columns, whose
 * ON UPDATE CURRENT_TIMESTAMP is a trigger on PostgreSQL
 * (createUpdatedAtTrigger) and whose type and default are the same on both
 * engines; the spec proves the column moves on UPDATE on both.
 */

/**
 * The columns the MySQL track created as plain `tinyint` (TypeORM's
 * `boolean` on MySQL, read back as smallint) and the baseline as `boolean`,
 * whose default is then `false`/`true` instead of `0`/`1`.
 */
const TINYINT_BOOLEANS: Record<string, string[]> = {
  correspondance_table: ['enabled'],
  generated_reports: ['detailed'],
  sca_autofix_records: [
    'hasFixAvailable',
    'isTransitive',
    'recommendedFixIsValid',
  ],
  sca_detected_packages: ['dependencyInfoAvailable', 'isDev', 'isTransitive'],
};

/** Every json column: jsonb on PostgreSQL (columnType). */
const JSON_COLUMNS: Record<string, string[]> = {
  autofix_records: ['edits'],
  code_snippet: ['code'],
  data_flow_item: ['code'],
  organization_statistics: ['stats'],
  sca_autofix_records: ['dependencyPath', 'fixCandidates'],
  vulnerability: ['codeExamples', 'cvss3', 'sourceMetadata'],
  vulnerability_osv: ['database_specific', 'related', 'upstream'],
  vulnerability_osv_affected: [
    'databaseSpecific',
    'ecosystemSpecific',
    'severity',
    'versions',
  ],
};

const BOOLEAN_ALLOWANCES: ParityAllowance[] = Object.entries(
  TINYINT_BOOLEANS,
).flatMap(([table, columns]) =>
  columns.flatMap((column): ParityAllowance[] => {
    const allowances: ParityAllowance[] = [
      {
        table,
        column,
        aspect: 'type',
        reason: 'boolean column: tinyint on MySQL, boolean on PostgreSQL',
      },
    ];
    // isDev and isTransitive of sca_detected_packages have no default.
    if (
      !(
        table === 'sca_detected_packages' &&
        column !== 'dependencyInfoAvailable'
      )
    ) {
      allowances.push({
        table,
        column,
        aspect: 'default',
        reason:
          'boolean column: default 0/1 on MySQL, false/true on PostgreSQL',
      });
    }
    return allowances;
  }),
);

const JSONB = 'PostgreSQL stores json columns as jsonb (columnType)';
const JSON_ALLOWANCES: ParityAllowance[] = Object.entries(JSON_COLUMNS).flatMap(
  ([table, columns]) =>
    columns.map(
      (column): ParityAllowance => ({
        table,
        column,
        aspect: 'type',
        reason: JSONB,
      }),
    ),
);

const CITEXT =
  'compared case-insensitively by the code (ciText): varchar under the MySQL collation, citext on PostgreSQL';
const LICENSE_IGNORED =
  "the entity declares columnType('tinyint') (smallint on PostgreSQL) and the code writes 0/1; the MySQL migration created it as tinyint(1), read back as boolean";

export const SCHEMA_PARITY_ALLOW: ParityAllowance[] = [
  {
    table: '*',
    column: 'id',
    aspect: 'default',
    reason:
      'PostgreSQL ids default to gen_random_uuid()::text (UuidPrimaryColumn); MySQL ids are generated by TypeORM',
  },
  {
    table: 'sca_detected_packages',
    column: 'packageName',
    aspect: 'type',
    reason: CITEXT,
  },
  {
    table: 'sca_detected_packages',
    column: 'packageVersion',
    aspect: 'type',
    reason: CITEXT,
  },
  {
    table: 'container_detected_images',
    column: 'artifactName',
    aspect: 'type',
    reason: CITEXT,
  },
  {
    table: 'sca_detected_packages',
    column: 'isLicenseIgnored',
    aspect: 'type',
    reason: LICENSE_IGNORED,
  },
  {
    table: 'sca_detected_packages',
    column: 'isLicenseIgnored',
    aspect: 'default',
    reason: LICENSE_IGNORED,
  },
  ...JSON_ALLOWANCES,
  ...BOOLEAN_ALLOWANCES,
];
