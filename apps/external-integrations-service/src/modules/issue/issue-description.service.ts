import { Inject, Injectable } from '@nestjs/common';

import { VulnerabilityInfo } from '@grpc/external-integrations/issue';
import {
  PRODUCT_LINKS_PORT,
  type ProductLinksPort,
} from '../../edition/ports/product-links.port';

/**
 * Service for generating issue descriptions that can be reused
 * across GitHub, GitLab, and Jira integrations.
 *
 * The generated descriptions are platform-agnostic Markdown format.
 */
@Injectable()
export class IssueDescriptionService {
  constructor(
    @Inject(PRODUCT_LINKS_PORT)
    private readonly productLinks: ProductLinksPort,
  ) {}

  /**
   * Generate issue content for a single vulnerability.
   * Used with ISSUE_CREATION_MODE_PER_VULNERABILITY mode.
   */
  generateSingleVulnerabilityIssue(vulnerability: VulnerabilityInfo): {
    title: string;
    body: string;
  } {
    const title = this.buildSingleVulnerabilityTitle(vulnerability);
    const body = this.buildSingleVulnerabilityBody(vulnerability);
    return { title, body };
  }

  /**
   * Generate issue content for a group of vulnerabilities of the same type.
   * Used with ISSUE_CREATION_MODE_PER_VULNERABILITY_TYPE mode.
   */
  generateVulnerabilityTypeIssue(
    vulnerabilities: VulnerabilityInfo[],
    vulnerabilityType: string,
  ): { title: string; body: string } {
    const title = this.buildVulnerabilityTypeTitle(
      vulnerabilities,
      vulnerabilityType,
    );
    const body = this.buildVulnerabilityTypeBody(
      vulnerabilities,
      vulnerabilityType,
    );
    return { title, body };
  }

  /**
   * Generate issue content for all vulnerabilities in a single file.
   * Used with ISSUE_CREATION_MODE_PER_FILE mode.
   */
  generateFileIssue(
    vulnerabilities: VulnerabilityInfo[],
    filePath: string,
  ): { title: string; body: string } {
    const title = this.buildFileIssueTitle(vulnerabilities, filePath);
    const body = this.buildFileIssueBody(vulnerabilities, filePath);
    return { title, body };
  }

  /**
   * Generate a closing comment when vulnerabilities are resolved.
   */
  generateClosingComment(reason: string, vulnerabilityCount: number): string {
    const reasonText = this.getReasonText(reason);
    return [
      '## 🎉 Issue Resolved by CybeDefend',
      '',
      `This issue has been automatically closed because ${vulnerabilityCount} vulnerability(ies) ${reasonText}.`,
      '',
      '---',
      this.footer('This comment was generated by'),
    ].join('\n');
  }

  /**
   * Generate an update comment when new vulnerabilities are found.
   */
  generateUpdateComment(newVulnerabilities: VulnerabilityInfo[]): string {
    const lines = [
      '## 🔄 Update from CybeDefend',
      '',
      `${newVulnerabilities.length} additional occurrence(s) of this vulnerability have been detected:`,
      '',
    ];

    for (const vuln of newVulnerabilities.slice(0, 10)) {
      const locationPart =
        vuln.startLine > 0 ? ` (Line ${vuln.startLine})` : '';
      lines.push(
        `- **${vuln.filePath}**${locationPart} - [View in CybeDefend](${vuln.cybedefendUrl})`,
      );
    }

    if (newVulnerabilities.length > 10) {
      lines.push(
        '',
        `... and ${newVulnerabilities.length - 10} more occurrences.`,
      );
    }

    lines.push('', '---', this.footer('This comment was generated by'));

    return lines.join('\n');
  }

  /**
   * The italic line that closes a ticket or a comment: the product named, and
   * linked to the address the edition gives (a self-hosted instance's own
   * dashboard), or named alone when there is none.
   */
  private footer(lead: string): string {
    const url = this.productLinks.ticketFooterUrl();
    return url ? `*${lead} [CybeDefend](${url})*` : `*${lead} CybeDefend*`;
  }

  // ==================== Private Title Builders ====================

  private buildSingleVulnerabilityTitle(
    vulnerability: VulnerabilityInfo,
  ): string {
    const severityEmoji = this.getSeverityEmoji(vulnerability.severity);
    const scannerLabel = this.getScannerLabel(vulnerability.scannerType);

    if (vulnerability.scannerType === 'sca') {
      return `${severityEmoji} [${scannerLabel}] ${vulnerability.externalId || vulnerability.name} in ${vulnerability.packageName}@${vulnerability.packageVersion}`;
    }

    const fileName =
      vulnerability.filePath.split('/').pop() || vulnerability.filePath;
    return `${severityEmoji} [${scannerLabel}] ${vulnerability.name} in ${fileName}`;
  }

  private buildVulnerabilityTypeTitle(
    vulnerabilities: VulnerabilityInfo[],
    vulnerabilityType: string,
  ): string {
    const highestSeverity = this.getHighestSeverity(vulnerabilities);
    const severityEmoji = this.getSeverityEmoji(highestSeverity);
    const count = vulnerabilities.length;
    const scannerType = vulnerabilities[0]?.scannerType || 'unknown';
    const scannerLabel = this.getScannerLabel(scannerType);

    return `${severityEmoji} [${scannerLabel}] ${vulnerabilityType} (${count} occurrence${count > 1 ? 's' : ''})`;
  }

  private buildFileIssueTitle(
    vulnerabilities: VulnerabilityInfo[],
    filePath: string,
  ): string {
    const highestSeverity = this.getHighestSeverity(vulnerabilities);
    const severityEmoji = this.getSeverityEmoji(highestSeverity);
    const count = vulnerabilities.length;
    const fileName = filePath.split('/').pop() || filePath;

    return `${severityEmoji} Security Issues in ${fileName} (${count} finding${count > 1 ? 's' : ''})`;
  }

  // ==================== Private Body Builders ====================

  private buildSingleVulnerabilityBody(
    vulnerability: VulnerabilityInfo,
  ): string {
    const sections: string[] = [];

    // Header
    sections.push('## 🔐 Security Vulnerability Detected by CybeDefend');
    sections.push('');

    // Branch tag
    if (vulnerability.branch) {
      sections.push(`> 🌿 **Branch**: \`${vulnerability.branch}\``);
      sections.push('');
    }

    // Summary table
    sections.push('| Property | Value |');
    sections.push('|----------|-------|');
    sections.push(
      `| **Severity** | ${this.formatSeverity(vulnerability.severity)} |`,
    );
    sections.push(
      `| **Scanner** | ${this.getScannerLabel(vulnerability.scannerType)} |`,
    );

    if (vulnerability.cvssScore > 0) {
      sections.push(
        `| **CVSS Score** | ${vulnerability.cvssScore.toFixed(1)} |`,
      );
    }

    if (vulnerability.externalId) {
      sections.push(`| **ID** | ${vulnerability.externalId} |`);
    }

    if (vulnerability.filePath) {
      sections.push(`| **File** | \`${vulnerability.filePath}\` |`);
    }

    if (vulnerability.startLine > 0) {
      const lineRange =
        vulnerability.endLine > vulnerability.startLine
          ? `${vulnerability.startLine}-${vulnerability.endLine}`
          : `${vulnerability.startLine}`;
      sections.push(`| **Line(s)** | ${lineRange} |`);
    }

    if (vulnerability.packageName) {
      sections.push(
        `| **Package** | ${vulnerability.packageName}@${vulnerability.packageVersion} |`,
      );
      if (vulnerability.fixedVersion) {
        sections.push(`| **Fixed Version** | ${vulnerability.fixedVersion} |`);
      }
    }

    sections.push('');

    // Description
    if (vulnerability.description) {
      sections.push('### Description');
      sections.push('');
      sections.push(vulnerability.description);
      sections.push('');
    } else if (vulnerability.shortDescription) {
      sections.push('### Description');
      sections.push('');
      sections.push(vulnerability.shortDescription);
      sections.push('');
    }

    // CWE / OWASP
    if (vulnerability.cwe.length > 0 || vulnerability.owaspTop10.length > 0) {
      sections.push('### References');
      sections.push('');
      if (vulnerability.cwe.length > 0) {
        sections.push(`- **CWE**: ${vulnerability.cwe.join(', ')}`);
      }
      if (vulnerability.owaspTop10.length > 0) {
        sections.push(
          `- **OWASP Top 10**: ${vulnerability.owaspTop10.join(', ')}`,
        );
      }
      sections.push('');
    }

    // CybeDefend link
    sections.push('### View in CybeDefend');
    sections.push('');
    sections.push(
      `[📊 View detailed analysis and remediation guidance](${vulnerability.cybedefendUrl})`,
    );
    sections.push('');

    // Footer
    sections.push('---');
    sections.push(this.footer('This issue was automatically created by'));

    return sections.join('\n');
  }

  private buildVulnerabilityTypeBody(
    vulnerabilities: VulnerabilityInfo[],
    vulnerabilityType: string,
  ): string {
    const sections: string[] = [];
    const first = vulnerabilities[0];

    // Header
    sections.push('## 🔐 Security Vulnerabilities Detected by CybeDefend');
    sections.push('');

    // Branch tag
    if (first?.branch) {
      sections.push(`> 🌿 **Branch**: \`${first.branch}\``);
      sections.push('');
    }

    // Summary
    const highestSeverity = this.getHighestSeverity(vulnerabilities);
    sections.push(
      `**${vulnerabilities.length}** occurrence(s) of **${vulnerabilityType}** detected.`,
    );
    sections.push('');
    sections.push(
      `**Highest Severity**: ${this.formatSeverity(highestSeverity)}`,
    );
    sections.push('');

    // Description from first vulnerability
    if (first?.description || first?.shortDescription) {
      sections.push('### Description');
      sections.push('');
      sections.push(first.description || first.shortDescription);
      sections.push('');
    }

    // Occurrences list
    sections.push('### Affected Locations');
    sections.push('');

    // Group by file
    const byFile = new Map<string, VulnerabilityInfo[]>();
    for (const vuln of vulnerabilities) {
      const file = vuln.filePath || 'Unknown';
      const existing = byFile.get(file) || [];
      existing.push(vuln);
      byFile.set(file, existing);
    }

    let displayedCount = 0;
    const maxDisplay = 20;

    for (const [file, vulns] of byFile) {
      if (displayedCount >= maxDisplay) break;

      sections.push(`#### \`${file}\``);
      for (const vuln of vulns) {
        if (displayedCount >= maxDisplay) break;

        const severity = this.formatSeverity(vuln.severity);
        if (vuln.startLine > 0) {
          sections.push(
            `- Line ${vuln.startLine} - ${severity} - [View](${vuln.cybedefendUrl})`,
          );
        } else {
          sections.push(`- ${severity} - [View](${vuln.cybedefendUrl})`);
        }
        displayedCount++;
      }
      sections.push('');
    }

    if (vulnerabilities.length > maxDisplay) {
      sections.push(
        `*... and ${vulnerabilities.length - maxDisplay} more occurrences*`,
      );
      sections.push('');
    }

    // CWE / OWASP from first
    if (first?.cwe?.length > 0 || first?.owaspTop10?.length > 0) {
      sections.push('### References');
      sections.push('');
      if (first.cwe.length > 0) {
        sections.push(`- **CWE**: ${first.cwe.join(', ')}`);
      }
      if (first.owaspTop10.length > 0) {
        sections.push(`- **OWASP Top 10**: ${first.owaspTop10.join(', ')}`);
      }
      sections.push('');
    }

    // Footer
    sections.push('---');
    sections.push(this.footer('This issue was automatically created by'));

    return sections.join('\n');
  }

  private buildFileIssueBody(
    vulnerabilities: VulnerabilityInfo[],
    filePath: string,
  ): string {
    const sections: string[] = [];
    const first = vulnerabilities[0];

    // Header
    sections.push('## 🔐 Security Findings in File');
    sections.push('');

    // Branch tag
    if (first?.branch) {
      sections.push(`> 🌿 **Branch**: \`${first.branch}\``);
      sections.push('');
    }

    sections.push(`**File**: \`${filePath}\``);
    sections.push('');

    // Summary by severity
    const bySeverity = this.groupBySeverity(vulnerabilities);
    sections.push('### Summary');
    sections.push('');
    sections.push('| Severity | Count |');
    sections.push('|----------|-------|');
    for (const sev of ['critical', 'high', 'medium', 'low']) {
      const count = bySeverity.get(sev)?.length || 0;
      if (count > 0) {
        sections.push(`| ${this.formatSeverity(sev)} | ${count} |`);
      }
    }
    sections.push('');

    // Vulnerabilities list
    sections.push('### Findings');
    sections.push('');

    // Sort by line number
    const sorted = [...vulnerabilities].sort(
      (a, b) => a.startLine - b.startLine,
    );

    for (const vuln of sorted.slice(0, 30)) {
      sections.push(`#### ${vuln.name}`);
      sections.push('');
      if (vuln.startLine > 0) {
        sections.push(`- **Location**: Line ${vuln.startLine}`);
      }
      sections.push(`- **Severity**: ${this.formatSeverity(vuln.severity)}`);
      sections.push(`- **Scanner**: ${this.getScannerLabel(vuln.scannerType)}`);
      if (vuln.shortDescription) {
        sections.push(`- **Description**: ${vuln.shortDescription}`);
      }
      sections.push(`- [View in CybeDefend](${vuln.cybedefendUrl})`);
      sections.push('');
    }

    if (vulnerabilities.length > 30) {
      sections.push(`*... and ${vulnerabilities.length - 30} more findings*`);
      sections.push('');
    }

    // Footer
    sections.push('---');
    sections.push(this.footer('This issue was automatically created by'));

    return sections.join('\n');
  }

  // ==================== Helper Methods ====================

  private getSeverityEmoji(severity: string): string {
    switch (severity?.toLowerCase()) {
      case 'critical':
        return '🔴';
      case 'high':
        return '🟠';
      case 'medium':
        return '🟡';
      case 'low':
        return '🟢';
      default:
        return '⚪';
    }
  }

  private formatSeverity(severity: string): string {
    const emoji = this.getSeverityEmoji(severity);
    const text = severity?.toUpperCase() || 'UNKNOWN';
    return `${emoji} ${text}`;
  }

  private getScannerLabel(scannerType: string): string {
    switch (scannerType?.toLowerCase()) {
      case 'sast':
        return 'SAST';
      case 'sca':
        return 'SCA';
      case 'iac':
        return 'IaC';
      case 'container':
        return 'Container';
      case 'secret':
        return 'Secret';
      default:
        return scannerType?.toUpperCase() || 'Security';
    }
  }

  private getHighestSeverity(vulnerabilities: VulnerabilityInfo[]): string {
    const severityOrder = ['critical', 'high', 'medium', 'low'];
    for (const severity of severityOrder) {
      if (vulnerabilities.some((v) => v.severity?.toLowerCase() === severity)) {
        return severity;
      }
    }
    return 'medium';
  }

  private groupBySeverity(
    vulnerabilities: VulnerabilityInfo[],
  ): Map<string, VulnerabilityInfo[]> {
    const groups = new Map<string, VulnerabilityInfo[]>();
    for (const vuln of vulnerabilities) {
      const severity = vuln.severity?.toLowerCase() || 'medium';
      const existing = groups.get(severity) || [];
      existing.push(vuln);
      groups.set(severity, existing);
    }
    return groups;
  }

  private getReasonText(reason: string): string {
    switch (reason?.toLowerCase()) {
      case 'resolved':
        return 'have been fixed';
      case 'ignored':
        return 'have been marked as ignored';
      case 'false_positive':
        return 'have been marked as false positives';
      default:
        return 'have been resolved';
    }
  }
}
