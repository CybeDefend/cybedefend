import type { ParityAllowance } from '@cybedefend/db-dialect';

/**
 * The differences schema-parity.live.spec.ts accepts between the frozen MySQL
 * track and the PostgreSQL baseline, one line each with its reason. Nothing
 * goes here without a reason a reviewer can check; an entry that matches
 * nothing fails the spec.
 */

/**
 * The boolean columns the MySQL migrations declared as plain `tinyint` (read
 * back as smallint) and the entities as `boolean`. The comparison covers the
 * tables of the core entities only.
 */
const TINYINT_BOOLEANS: Record<string, string[]> = {
  github_repositories: ['private'],
  gitlab_repositories: ['private'],
};

const BOOLEAN_ALLOWANCES: ParityAllowance[] = Object.entries(
  TINYINT_BOOLEANS,
).flatMap(([table, columns]) =>
  columns.map(
    (column): ParityAllowance => ({
      table,
      column,
      aspect: 'type',
      reason: 'boolean column: tinyint on MySQL, boolean on PostgreSQL',
    }),
  ),
);

export const SCHEMA_PARITY_ALLOW: ParityAllowance[] = [
  {
    table: '*',
    column: 'id',
    aspect: 'default',
    reason:
      'PostgreSQL ids default to gen_random_uuid()::text (UuidPrimaryColumn); MySQL ids are generated by TypeORM',
  },
  // The entity declares a tinyint flag (columnType('tinyint')), which
  // PostgreSQL maps to smallint; the MySQL migration created tinyint(1),
  // which reads back as boolean.
  {
    table: 'jira_project_mappings',
    column: 'autoCreateEnabled',
    aspect: 'type',
    reason:
      'tinyint flag column: tinyint(1) (boolean) on MySQL, smallint on PostgreSQL (columnType)',
  },
  {
    table: 'jira_project_mappings',
    column: 'autoCreateEnabled',
    aspect: 'default',
    reason:
      'tinyint flag column: default 0 read as false on MySQL, 0 on PostgreSQL',
  },
  ...BOOLEAN_ALLOWANCES,
];
