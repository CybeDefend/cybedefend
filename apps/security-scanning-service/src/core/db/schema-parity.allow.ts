import type { ParityAllowance } from '@cybedefend/db-dialect';

/**
 * The differences schema-parity.live.spec.ts accepts between the frozen MySQL
 * track and the PostgreSQL baseline, one line each with its reason. Nothing
 * goes here without a reason a reviewer can check; an entry that matches
 * nothing fails the spec.
 */

/**
 * The boolean columns the MySQL track created as plain `tinyint` (read back as
 * smallint) and the baseline as `boolean`, whose default is then `false`/`true`
 * instead of `0`/`1`. The boolean columns a later MySQL migration declared
 * `tinyint(1)` or `BOOLEAN` read back as boolean on both engines and are not
 * listed.
 */
const TINYINT_BOOLEANS: Record<string, string[]> = {
  scan: ['private'],
  scanner: ['enabled', 'deletePodsOnFinish', 'deletePodsOnError'],
};

const BOOLEAN_ALLOWANCES: ParityAllowance[] = Object.entries(
  TINYINT_BOOLEANS,
).flatMap(([table, columns]) =>
  columns.flatMap((column): ParityAllowance[] => [
    {
      table,
      column,
      aspect: 'type',
      reason: 'boolean column: tinyint on MySQL, boolean on PostgreSQL',
    },
    {
      table,
      column,
      aspect: 'default',
      reason: 'boolean column: default 0/1 on MySQL, false/true on PostgreSQL',
    },
  ]),
);

const JSONB = 'PostgreSQL stores json columns as jsonb (columnType)';

export const SCHEMA_PARITY_ALLOW: ParityAllowance[] = [
  {
    table: '*',
    column: 'id',
    aspect: 'default',
    reason:
      'PostgreSQL ids default to gen_random_uuid()::text (UuidPrimaryColumn); MySQL ids are generated by TypeORM',
  },
  {
    table: 'scan',
    column: 'metadata',
    aspect: 'type',
    reason: JSONB,
  },
  ...BOOLEAN_ALLOWANCES,
];
