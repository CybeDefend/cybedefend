const BOOLEAN_ALLOWANCES: ParityAllowance[] = Object.entries(
  TINYINT_BOOLEANS,
).flatMap(([table, columns]) =>
  columns.flatMap((column): ParityAllowance[] => [
    {
      table,
      column,
      aspect: 'type',
      reason: 'boolean column: tinyint on MySQL, boolean on PostgreSQL',
    },
    {
      table,
      column,
      aspect: 'default',
      reason: 'boolean column: default 0/1 on MySQL, false/true on PostgreSQL',
    },
  ]),
);

const JSONB = 'PostgreSQL stores json columns as jsonb (columnType)';
const CITEXT =
  'compared case-insensitively by the code (ciText): varchar under the MySQL collation, citext on PostgreSQL';
const NO_MYSQL_FK =
  "the MySQL migration's guard compares COUNT(*), a string under TypeORM's bigNumberStrings, to the number 0, so it never added " +
  'the foreign key the entity declares (ON DELETE CASCADE); the baseline keeps it';

